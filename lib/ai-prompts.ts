const SYSTEM_PROMPT = `Ты — алгоритмический инструмент института ИЖСИЗ (системно-расстановочный подход).
Стиль: бережный, глубокий, исследовательский, профессиональный, спокойный.
ЯЗЫК: отвечай ТОЛЬКО на русском языке. Категорически запрещены английские и любые латинские слова (duels, balance, definitive и т.п.) — только русские эквиваленты. Запрещены иероглифы и любые другие языки.
ЗАПРЕЩЕНО: диагнозы, жёсткие предписания, гарантии исцеления, манипуляции, имитация живого специалиста.
Формулировки — только как гипотезы. Используй markdown-заголовки ## для разделов.
Начинай ответ сразу с первого заголовка ##. Не выводи план, рассуждения, чеклисты и метакомментарии.
Под каждым заголовком обязательно напиши содержательный текст: 2–5 предложений или маркированный список.`;

export function buildInsightographPrompt(payload: Record<string, unknown>) {
  return `${SYSTEM_PROMPT}

Проанализируй карту «Инсайтограф» пользователя. Данные:
${JSON.stringify(payload, null, 2)}

Структура ответа (обязательно все разделы):
## Главная смысловая линия
## Причинно-следственные связки и ограничивающие убеждения
## Ценностные слияния и сужения понятия
## Внутренние ресурсы (из ответов пользователя)
## Более гибкие альтернативные формулировки
## Вопросы для самостоятельного исследования`;
}

export function buildSixteenAssociationsPrompt(payload: Record<string, unknown>) {
  return `${SYSTEM_PROMPT}

Проанализируй карту «16 ассоциаций». Данные:
${JSON.stringify(payload, null, 2)}

Структура ответа (обязательно все разделы):
## Исходный запрос и итоговое ключевое слово
## Главная сквозная смысловая линия
## Уровень первичных ассоциаций (поверхностный слой)
## Второй уровень (личные смыслы и стратегии)
## Третий уровень (эмоционально-смысловой слой)
## Два ключевых направления (дополнение или конфликт)
## Потенциальные конфликты и ограничивающие установки (гипотезы)
## Внутренние ресурсы
## 5–10 вопросов для самоисследования и следующие шаги в Институте`;
}

export function buildNluPrompt(payload: Record<string, unknown>) {
  return `${SYSTEM_PROMPT}

Проанализируй карту «НЛУ ИЖСИЗ». Данные:
${JSON.stringify(payload, null, 2)}

Структура ответа (обязательно все разделы):
## Исходный запрос
## Уровень ощущений и тела
## Уровень убеждений и смыслов
## Уровень поведения и стратегий
## Уровень ценностей и идентичности
## Связи между уровнями (гипотезы)
## Внутренние ресурсы
## Вопросы для самоисследования`;
}

export function buildToolPrompt(tool: string, payload: Record<string, unknown>) {
  switch (tool) {
    case "insightograph":
      return buildInsightographPrompt(payload);
    case "sixteen_associations":
      return buildSixteenAssociationsPrompt(payload);
    case "nlu":
      return buildNluPrompt(payload);
    default:
      return `${SYSTEM_PROMPT}\n\nДанные:\n${JSON.stringify(payload, null, 2)}`;
  }
}
